#!/usr/bin/env node
/**
 * Keeps the apps' API identical to the websites'. Generates two files from
 * the web's single source (never edit the generated ones):
 *
 *   shared/src/services/endpoints.js  →  packages/core/api/endpoints.generated.js
 *       every server call (the apps can't load files outside mobile/)
 *   shared/src/services/api.js        →  packages/core/api/hooks.ts
 *       the same hook names the websites use (useGetMeQuery…)
 *
 * After adding or changing a call in shared/: npm run sync:api (from mobile/)
 * CI runs npm run check:api and fails if either file is out of date.
 */
const fs = require('fs');
const path = require('path');

const shared = path.resolve(__dirname, '../../shared/src/services');
const outDir = path.resolve(__dirname, '../packages/core/api');
const BANNER = (from) => `/**
 * GENERATED by mobile/tools/sync-api-hooks.js from shared/src/services/${from}.
 * Do not edit: change the shared file, then run \`npm run sync:api\` from mobile/.
 */
/* eslint-disable */
`;

// 1. The call list, copied as-is.
const endpointsSrc = fs.readFileSync(path.join(shared, 'endpoints.js'), 'utf8');
const endpointsOut = BANNER('endpoints.js') + endpointsSrc;

// 2. The hook names, bound to the apps' API.
const apiSrc = fs.readFileSync(path.join(shared, 'api.js'), 'utf8');
const block = apiSrc.slice(apiSrc.indexOf('export const {'), apiSrc.indexOf('} = api;'));
const names = [...new Set([...block.matchAll(/\b(use[A-Z]\w*)\b/g)].map((m) => m[1]))];
if (names.length < 100) throw new Error(`Only ${names.length} hooks found in api.js; did the export block move?`);
const hooksOut = `${BANNER('api.js')}import { api } from './sharedApi';

// The call list is plain JavaScript, so its hooks are untyped here.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const h = api as unknown as Record<string, any>;

${names.map((n) => `export const ${n} = h.${n};`).join('\n')}
`;

const files = [
  [path.join(outDir, 'endpoints.generated.js'), endpointsOut],
  [path.join(outDir, 'hooks.ts'), hooksOut],
];

if (process.argv.includes('--check')) {
  const stale = files.filter(([f, text]) => !fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== text);
  if (stale.length) {
    console.error(`Out of date: ${stale.map(([f]) => path.basename(f)).join(', ')}. Run: npm run sync:api`);
    process.exit(1);
  }
  console.log(`API in sync with the websites (${names.length} hooks).`);
} else {
  for (const [f, text] of files) fs.writeFileSync(f, text);
  console.log(`Synced ${names.length} hooks and the call list from shared/src/services.`);
}
