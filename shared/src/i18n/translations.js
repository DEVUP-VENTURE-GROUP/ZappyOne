/**
 * Normalize a service display name into its svc.* translation key.
 * e.g. "WiFi Setup" → "svc.wifi_setup", "Screen Replacement" → "svc.screen_replacement".
 * Use with t(): t(serviceNameKey(name), name) — falls back to the English name.
 */
// A ServicePro label's key from its English text, so a trade's own words ("Mechanics", "Garage & hours") translate too.
export function labelKey(label = '') {
  return 'sp.' + String(label).toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}

export function serviceNameKey(name = '') {
  return 'svc.' + name.toLowerCase().trim().replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}

